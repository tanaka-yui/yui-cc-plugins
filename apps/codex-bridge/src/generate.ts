import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, isAbsolute, join, relative, sep } from 'node:path'

export const SENTINEL = 'GENERATED by codex-bridge'
export const SIZE_LIMIT = 32768
/** --global の出力の target。 */
export const GLOBAL_TARGET = '<global>'

export interface RuleAttrs {
  codexTargets: string[]
  description: string | null
}

function stripQuotes(value: string): string {
  return value.replace(/^['"]|['"]$/g, '').trim()
}

function parseAttrs(raw: string): RuleAttrs {
  const targets: string[] = []
  let description: string | null = null
  let inTargets = false
  for (const line of raw.split(/\r?\n/)) {
    const listMatch = line.match(/^\s*-\s+(.+?)\s*$/)
    if (inTargets && listMatch) {
      targets.push(stripQuotes(listMatch[1] ?? ''))
      continue
    }
    inTargets = false
    const kv = line.match(/^([A-Za-z0-9_]+):\s*(.*)$/)
    if (!kv) continue
    const key = kv[1] ?? ''
    const value = (kv[2] ?? '').trim()
    if (key === 'codexTargets') {
      if (value.startsWith('[')) {
        const inner = value.slice(1, value.endsWith(']') ? -1 : value.length)
        for (const part of inner.split(',')) {
          const target = stripQuotes(part.trim())
          if (target) targets.push(target)
        }
      } else if (value === '') {
        inTargets = true
      }
    } else if (key === 'description') {
      description = value === '' ? null : stripQuotes(value)
    }
  }
  return { codexTargets: targets, description }
}

export function parseFrontmatter(content: string): { attrs: RuleAttrs; body: string } {
  const empty: RuleAttrs = { codexTargets: [], description: null }
  if (!content.startsWith('---\n') && !content.startsWith('---\r\n')) {
    return { attrs: empty, body: content }
  }
  const end = content.indexOf('\n---', 4)
  if (end === -1) return { attrs: empty, body: content }
  const raw = content.slice(4, end)
  const body = content.slice(end + 4).replace(/^\r?\n/, '')
  return { attrs: parseAttrs(raw), body }
}

export function renderAgentsFile(sources: string[], bodies: string[]): string {
  const header = `<!-- ${SENTINEL}. DO NOT EDIT.\n     Source: ${sources.join(', ')} -->`
  const merged = bodies.map((b) => b.trim()).join('\n\n')
  return `${header}\n\n${merged}\n`
}

export function hasSentinel(content: string): boolean {
  return content.includes(SENTINEL)
}

export interface RuleInput {
  file: string
  targets: string[]
  body: string
}

export interface TargetGroup {
  target: string
  members: { file: string; body: string }[]
}

export function groupRulesByTarget(rules: RuleInput[]): { groups: TargetGroup[]; unmapped: string[] } {
  const byTarget = new Map<string, { file: string; body: string }[]>()
  const unmapped: string[] = []
  for (const rule of rules) {
    if (rule.targets.length === 0) {
      unmapped.push(rule.file)
      continue
    }
    for (const target of rule.targets) {
      const members = byTarget.get(target) ?? []
      members.push({ file: rule.file, body: rule.body })
      byTarget.set(target, members)
    }
  }
  const groups: TargetGroup[] = [...byTarget.keys()].sort().map((target) => ({
    target,
    members: (byTarget.get(target) ?? []).sort((a, b) => a.file.localeCompare(b.file)),
  }))
  return { groups, unmapped: unmapped.sort() }
}

export type WriteDecision = { action: 'write' } | { action: 'skip-handwritten' }

export function decideWrite(existing: string | null, _next: string): WriteDecision {
  if (existing === null) return { action: 'write' }
  if (hasSentinel(existing)) return { action: 'write' }
  return { action: 'skip-handwritten' }
}

/** `--max-bytes 65536` / `--max-bytes=65536` を読む。正の整数でなければ null。 */
export function parseMaxBytesFlag(argv: string[]): number | null {
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i] ?? ''
    const inline = arg.match(/^--max-bytes=(.*)$/)
    const raw = inline ? inline[1] : arg === '--max-bytes' ? argv[i + 1] : null
    if (raw == null) continue
    if (!/^\d+$/.test(raw)) return null
    const value = Number.parseInt(raw, 10)
    return value > 0 ? value : null
  }
  return null
}

/**
 * `~/.codex/config.toml` の root テーブルにある `project_doc_max_bytes` を読む。
 * TOML を厳密に解釈はせず、最初の `[section]` より前の同名キーだけを見る
 * （codex はこのキーを root にしか置かないため、これで十分かつ誤検出しない）。
 */
export function parseProjectDocMaxBytes(toml: string): number | null {
  for (const line of toml.split(/\r?\n/)) {
    const trimmed = line.trim()
    if (trimmed.startsWith('#')) continue
    if (trimmed.startsWith('[')) return null
    const match = trimmed.match(/^project_doc_max_bytes\s*=\s*(\d+)\s*$/)
    if (match) {
      const value = Number.parseInt(match[1] ?? '', 10)
      return value > 0 ? value : null
    }
  }
  return null
}

/** bytes を収める最小の 2 の冪を返す（limit 以下なら limit のまま）。 */
export function suggestLimit(bytes: number, limit: number = SIZE_LIMIT): number {
  let suggested = limit
  while (suggested < bytes) suggested *= 2
  return suggested
}

export interface OutputSource {
  file: string
  bytes: number
}

export interface PlannedOutput {
  path: string
  content: string
  /** 生成先の codexTargets（root CLAUDE.md 由来なら '<root>'）。 */
  target: string
  /** 寄与した rule ファイルと、その本文バイト数。 */
  sources: OutputSource[]
}

export type OversizeKind = 'single-rule-over-limit' | 'concatenation-over-limit' | 'chain-over-limit'

/** Codex が読む 1 つの AGENTS.md（root から作業ディレクトリまでの連なりの 1 つ）。 */
export interface ChainFile {
  /** root からの相対パス（root の AGENTS.md は 'AGENTS.md'）。 */
  path: string
  bytes: number
  /** 生成物なら寄与した rule と本文のバイト数。手書きなら空。 */
  sources: OutputSource[]
}

export interface OversizeDiagnosis {
  /** 連なりの末端の AGENTS.md（root からの相対パス）。 */
  path: string
  /** 末端の生成先の codexTargets（root CLAUDE.md 由来なら '<root>'、global なら '<global>'）。 */
  target: string
  /** 連なりの合計バイト数。 */
  bytes: number
  limit: number
  overBy: number
  kind: OversizeKind
  chain: ChainFile[]
  /** 単体で limit を超えている rule。 */
  offenders: OutputSource[]
  suggestedLimit: number
  remedies: string[]
}

/**
 * Codex は root から作業ディレクトリまでの AGENTS.md を root 側から順に読み、合計が
 * project_doc_max_bytes に達したところで切り捨てる（上限は 1 ファイルごとではなく連なりの合計）。
 * 末端までの合計が上限を超えるなら、内訳と対処案を返す。収まるなら null。
 *
 * 種類の区別（取り違えると効かない対処を提案してしまう）:
 * - single-rule-over-limit: 1 つの rule だけで上限を超えている。`codexTargets` を付け替えても
 *   丸ごと移るだけなので、rule を分割するか削る。
 * - concatenation-over-limit: rule は収まるが、連なりの中の 1 つの AGENTS.md が単体で上限を超えている。
 *   その AGENTS.md の rule の一部を、より深い `codexTargets` に移す。
 * - chain-over-limit: どのファイルも単体では収まるが、root からの合計が超えている。いちばん大きい
 *   ファイルを削るかより深くへ移すか、リポジトリの `.codex/config.toml` で上限を上げる。
 */
export function diagnoseChain(
  leaf: { path: string; target: string },
  chain: ChainFile[],
  limit: number = SIZE_LIMIT,
): OversizeDiagnosis | null {
  const bytes = chain.reduce((sum, file) => sum + file.bytes, 0)
  if (bytes <= limit) return null
  const offenders = chain.flatMap((file) => file.sources).filter((source) => source.bytes > limit)
  const overFiles = chain.filter((file) => file.bytes > limit)
  const kind: OversizeKind =
    offenders.length > 0
      ? 'single-rule-over-limit'
      : overFiles.length > 0
        ? 'concatenation-over-limit'
        : 'chain-over-limit'
  const suggestedLimit = suggestLimit(bytes, limit)
  const remedies: string[] = []

  if (kind === 'single-rule-over-limit') {
    for (const offender of offenders) {
      remedies.push(
        `${offender.file} は単体で ${offender.bytes} bytes あり上限を超えている。` +
          `codexTargets の付け替えでは解決しないので、見出し単位でファイルを分割し、` +
          `分割後の各ファイルに別々の（より深い）codexTargets を割り当てる。`,
      )
    }
  } else if (kind === 'concatenation-over-limit') {
    for (const file of overFiles) {
      const largest = [...file.sources].sort((a, b) => b.bytes - a.bytes)[0]
      remedies.push(
        largest && file.sources.length > 1
          ? `${file.path}（${file.bytes} bytes）が単体で上限を超えている。いちばん大きい ${largest.file}` +
              `（${largest.bytes} bytes）をより深いディレクトリの codexTargets に移す。`
          : `${file.path}（${file.bytes} bytes）が単体で上限を超えている。元のファイルを分割するか内容を削る。`,
      )
    }
  } else {
    const largest = [...chain].sort((a, b) => b.bytes - a.bytes)[0]
    if (largest) {
      remedies.push(
        largest.path === 'AGENTS.md'
          ? `いちばん大きいのは root の AGENTS.md（${largest.bytes} bytes）。root の CLAUDE.md から、` +
              `特定の層だけに要る節を .claude/rules/ の範囲を絞った rule（より深い codexTargets）に移す。`
          : `いちばん大きいのは ${largest.path}（${largest.bytes} bytes）。その rule の一部をより深い ` +
              `codexTargets に移すか削る。`,
      )
    }
  }

  remedies.push(
    leaf.target === GLOBAL_TARGET
      ? `内容を減らせない場合は、~/.codex/config.toml に project_doc_max_bytes = ${suggestedLimit} を設定する` +
          `（~/.codex/AGENTS.md 自体がマシンローカルなので、マシンローカルの設定で足りる）。`
      : `内容を減らせない場合は、リポジトリの .codex/config.toml に project_doc_max_bytes = ${suggestedLimit} を` +
          `書いてコミットする（Codex がプロジェクトを信頼済みのときに効く）。~/.codex/config.toml は` +
          `マシンローカルで、他の開発者や CI には効かない。`,
  )

  return {
    path: leaf.path,
    target: leaf.target,
    bytes,
    limit,
    overBy: bytes - limit,
    kind,
    chain,
    offenders,
    suggestedLimit,
    remedies,
  }
}

export interface CollectResult {
  outputs: PlannedOutput[]
  warnings: string[]
}

async function pathExists(target: string): Promise<boolean> {
  try {
    await stat(target)
    return true
  } catch {
    return false
  }
}

export async function collectProjectOutputs(root: string): Promise<CollectResult> {
  const outputs: PlannedOutput[] = []
  const warnings: string[] = []

  const rulesDir = join(root, '.claude', 'rules')
  if (await pathExists(rulesDir)) {
    const entries = (await readdir(rulesDir)).filter((f) => f.endsWith('.md')).sort()
    const rules: RuleInput[] = []
    for (const file of entries) {
      const raw = await readFile(join(rulesDir, file), 'utf8')
      const { attrs, body } = parseFrontmatter(raw)
      rules.push({ file, targets: attrs.codexTargets, body })
    }
    const { groups, unmapped } = groupRulesByTarget(rules)
    for (const orphan of unmapped) {
      warnings.push(`未マッピング rule (codexTargets 無し): .claude/rules/${orphan}`)
    }
    for (const group of groups) {
      const targetDir = join(root, group.target)
      if (!(await pathExists(targetDir))) {
        warnings.push(`target ディレクトリが存在しないためスキップ: ${group.target}`)
        continue
      }
      const sources = group.members.map((m) => `.claude/rules/${m.file}`)
      const bodies = group.members.map((m) => m.body)
      outputs.push({
        path: join(targetDir, 'AGENTS.md'),
        content: renderAgentsFile(sources, bodies),
        target: group.target,
        sources: group.members.map((m) => ({
          file: `.claude/rules/${m.file}`,
          bytes: Buffer.byteLength(m.body.trim(), 'utf8'),
        })),
      })
    }
  } else {
    warnings.push('.claude/rules ディレクトリが見つかりません')
  }

  const claudeMd = join(root, 'CLAUDE.md')
  if (await pathExists(claudeMd)) {
    const content = await readFile(claudeMd, 'utf8')
    outputs.push({
      path: join(root, 'AGENTS.md'),
      content: renderAgentsFile(['CLAUDE.md'], [content]),
      target: '<root>',
      sources: [{ file: 'CLAUDE.md', bytes: Buffer.byteLength(content.trim(), 'utf8') }],
    })
  } else {
    warnings.push('root CLAUDE.md が見つかりません')
  }

  return { outputs, warnings }
}

export async function collectGlobalOutput(home: string): Promise<CollectResult> {
  const source = join(home, '.claude', 'CLAUDE.md')
  if (!(await pathExists(source))) {
    return { outputs: [], warnings: ['~/.claude/CLAUDE.md が見つかりません'] }
  }
  const content = await readFile(source, 'utf8')
  return {
    outputs: [
      {
        path: join(home, '.codex', 'AGENTS.md'),
        content: renderAgentsFile(['~/.claude/CLAUDE.md'], [content]),
        target: GLOBAL_TARGET,
        sources: [{ file: '~/.claude/CLAUDE.md', bytes: Buffer.byteLength(content.trim(), 'utf8') }],
      },
    ],
    warnings: [],
  }
}

export interface WriteReport {
  written: string[]
  skippedHandwritten: string[]
}

export async function writeOutputs(outputs: PlannedOutput[]): Promise<WriteReport> {
  const report: WriteReport = { written: [], skippedHandwritten: [] }
  for (const output of outputs) {
    const existing = (await pathExists(output.path)) ? await readFile(output.path, 'utf8') : null
    if (decideWrite(existing, output.content).action === 'skip-handwritten') {
      report.skippedHandwritten.push(output.path)
      continue
    }
    await mkdir(dirname(output.path), { recursive: true })
    await writeFile(output.path, output.content)
    report.written.push(output.path)
  }
  return report
}

/** root から dir までのディレクトリを root 側から返す（dir が root の外なら root だけ）。 */
export function ancestorDirs(root: string, dir: string): string[] {
  const rel = relative(root, dir)
  if (rel === '' || rel.startsWith('..') || isAbsolute(rel)) return [root]
  const dirs = [root]
  let current = root
  for (const part of rel.split(sep)) {
    current = join(current, part)
    dirs.push(current)
  }
  return dirs
}

/**
 * dir までに Codex が読む AGENTS.md の連なりを、いまのディスクから読む。手書きのファイルも数える。
 * 各ディレクトリで AGENTS.override.md があればそちらを、無ければ AGENTS.md を読む。
 * 空白だけのファイルは Codex が数えないので除く。
 */
export async function collectChain(
  root: string,
  dir: string,
  sourcesByPath: Map<string, OutputSource[]>,
): Promise<ChainFile[]> {
  const chain: ChainFile[] = []
  for (const current of ancestorDirs(root, dir)) {
    const override = join(current, 'AGENTS.override.md')
    const path = (await pathExists(override)) ? override : join(current, 'AGENTS.md')
    if (!(await pathExists(path))) continue
    const content = await readFile(path, 'utf8')
    if (content.trim() === '') continue
    chain.push({
      path: relative(root, path),
      bytes: Buffer.byteLength(content, 'utf8'),
      sources: sourcesByPath.get(path) ?? [],
    })
  }
  return chain
}

/**
 * 各出力について、root からその出力までの連なりの合計を確かめる。
 * --global では root を `~/.codex` にすると、`~/.codex/AGENTS.md`（または AGENTS.override.md）
 * 1 ファイルだけの連なりになる。
 */
export async function checkChains(
  root: string,
  outputs: PlannedOutput[],
  limit: number = SIZE_LIMIT,
): Promise<OversizeDiagnosis[]> {
  const sourcesByPath = new Map(outputs.map((output) => [output.path, output.sources]))
  const diagnoses: OversizeDiagnosis[] = []
  for (const output of outputs) {
    const chain = await collectChain(root, dirname(output.path), sourcesByPath)
    const diagnosis = diagnoseChain({ path: relative(root, output.path), target: output.target }, chain, limit)
    if (diagnosis) diagnoses.push(diagnosis)
  }
  return diagnoses
}

async function readLimitFrom(configPath: string): Promise<number | null> {
  return (await pathExists(configPath)) ? parseProjectDocMaxBytes(await readFile(configPath, 'utf8')) : null
}

/**
 * 有効な上限を決める。優先順位は `--max-bytes` > リポジトリの `.codex/config.toml` >
 * `~/.codex/config.toml` の `project_doc_max_bytes` > 既定の 32768
 * （Codex はプロジェクトの設定をユーザーの設定より優先する）。
 * root が null（--global）のときはプロジェクトの設定を見ない。
 */
export async function resolveSizeLimit(
  argv: string[],
  env: { root: string | null; home: string },
): Promise<{ limit: number; source: string }> {
  const flag = parseMaxBytesFlag(argv)
  if (flag !== null) return { limit: flag, source: '--max-bytes' }
  if (env.root !== null) {
    const fromProject = await readLimitFrom(join(env.root, '.codex', 'config.toml'))
    if (fromProject !== null) return { limit: fromProject, source: '.codex/config.toml（プロジェクト）' }
  }
  if (env.home !== '') {
    const fromHome = await readLimitFrom(join(env.home, '.codex', 'config.toml'))
    if (fromHome !== null) return { limit: fromHome, source: '~/.codex/config.toml' }
  }
  return { limit: SIZE_LIMIT, source: 'codex 既定値' }
}

const KIND_LABELS: Record<OversizeKind, string> = {
  'single-rule-over-limit': '単一 rule が上限超過',
  'concatenation-over-limit': '1 つの AGENTS.md が上限超過',
  'chain-over-limit': 'root からの合計が上限超過',
}

export function formatOversize(diagnosis: OversizeDiagnosis): string[] {
  const lines: string[] = []
  // kind は enum 値も併記する。commands/codex-bridge.md（英語必須）は表示ラベルではなく
  // この安定した識別子を見て分岐するため。
  lines.push(
    `  警告(上限 ${diagnosis.limit} bytes 超過, 切り捨てリスク): ${diagnosis.path} までの合計 = ` +
      `${diagnosis.bytes} bytes (+${diagnosis.overBy} / ${KIND_LABELS[diagnosis.kind]} [${diagnosis.kind}])`,
  )
  lines.push(`    内訳 (target: ${diagnosis.target}):`)
  for (const file of diagnosis.chain) {
    const mark = file.bytes > diagnosis.limit ? ' ← 単体で超過' : ''
    lines.push(`      - ${file.path}: ${file.bytes} bytes${mark}`)
    for (const source of [...file.sources].sort((a, b) => b.bytes - a.bytes)) {
      const sourceMark = source.bytes > diagnosis.limit ? ' ← 単体で超過' : ''
      lines.push(`          ${source.file}: ${source.bytes} bytes${sourceMark}`)
    }
  }
  lines.push('    対処案:')
  for (const [index, remedy] of diagnosis.remedies.entries()) {
    lines.push(`      ${index + 1}. ${remedy}`)
  }
  return lines
}

/** 生成して結果を表示する。合計が上限を超える連なりがあれば（書き込みはしたうえで）1 を返す。 */
export async function main(argv: string[], env: { cwd: string; home: string }): Promise<number> {
  const isGlobal = argv.includes('--global')
  // --global は ~/.codex を root とした 1 ファイルの連なりとして測る（プロジェクトの連なりは無い）。
  const chainRoot = isGlobal ? join(env.home, '.codex') : env.cwd
  const { limit, source: limitSource } = await resolveSizeLimit(argv, {
    root: isGlobal ? null : env.cwd,
    home: env.home,
  })
  const { outputs, warnings } = isGlobal ? await collectGlobalOutput(env.home) : await collectProjectOutputs(env.cwd)
  const report = await writeOutputs(outputs)
  const oversize = await checkChains(chainRoot, outputs, limit)

  console.log(
    `codex-bridge: ${isGlobal ? 'global' : 'project'} モードで実行 ` +
      `(上限 ${limit} bytes / ${chainRoot} からの合計 / ${limitSource})`,
  )
  for (const path of report.written) console.log(`  生成: ${path}`)
  for (const path of report.skippedHandwritten) console.log(`  スキップ(手書き): ${path}`)
  for (const diagnosis of oversize) {
    for (const line of formatOversize(diagnosis)) console.log(line)
  }
  for (const warning of warnings) console.log(`  警告: ${warning}`)
  console.log(
    `完了: ${report.written.length} 件生成 / ${report.skippedHandwritten.length} 件スキップ / ` +
      `${oversize.length} 件サイズ超過 / ${warnings.length} 件警告`,
  )
  return oversize.length > 0 ? 1 : 0
}
